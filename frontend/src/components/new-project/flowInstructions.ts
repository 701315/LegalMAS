/**
 * Возвращает инструкцию для правой колонки.
 * Если активного шага нет — возвращает FLOW_INTRO.
 */
export function getFlowInstruction(
  activeStep: number | null,
): FlowStepInstruction {
  if (activeStep === null) {
    return FLOW_INTRO;
  }

  return FLOW_STEP_INSTRUCTIONS[activeStep] ?? FLOW_INTRO;
}


