# src/engine/retrieval/tokenization.py

"""
Простейший счётчик "токенов" для чанка.

Для непрофессионального программиста:
- Здесь мы считаем токенами отдельные слова.
- В будущем этот модуль можно заменить на честный токенизатор
  (например, tiktoken для GPT-моделей), не меняя остальной код.
"""

from __future__ import annotations


def count_tokens(text: str) -> int:
    """
    Подсчитать количество "токенов" в строке.

    Сейчас:
    - Токен = слово, разделённое пробелами.
    - Это достаточно хорошо для грубого контроля размера чанков.

    Потом:
    - Можно будет заменить эту функцию на вызов настоящего токенизатора.
    """
    if not text:
        return 0
    # Разбиваем по пробелам и считаем непустые фрагменты.
    return len([w for w in text.split() if w])

