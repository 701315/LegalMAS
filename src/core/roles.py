# src/core/roles.py

"""
Общие типы ролей для всей системы (глобальные и проектные).

Задачи модуля:
- Дать единые типы для статической типизации (mypy, Pyright).
- Избежать дублирования строковых литералов ("admin", "editor", ...).
- Исключить циклические импорты: модуль не импортирует ORM, репозитории
  или FastAPI, только стандартную библиотеку.

ВАЖНО:
- Любые изменения набора ролей нужно сначала согласовать с фронтендом,
  так как он использует аналогичные union-типы (GlobalRole, ProjectRole).
"""

from __future__ import annotations

from typing import Literal

# ---------------------------
# Проектные роли (per-deal)
# ---------------------------

ProjectRole = Literal["admin", "editor", "viewer"]
"""
Роль пользователя на уровне конкретного проекта/сделки.

Семантика:
- "admin"  : полный доступ к проекту (загрузка/удаление документов,
             запуск анализов, управление участниками проекта и т.п.).
- "editor" : может изменять данные в проекте (загружать/редактировать),
             но не имеет полного админского контроля (по бизнес-логике).
- "viewer" : только просмотр данных по проекту, без разрушающих действий.

Эти значения должны совпадать с:
- фронтовым ProjectRole из src/api/auth.ts,
- значениями в таблице deal_members.role.
"""


# ---------------------------
# Глобальные роли (система)
# ---------------------------

GlobalRole = Literal[
    "superadmin",
    "admin",
    "reviewer",
    "editor",
    "viewer",
    "user",
    "system",
]
"""
Глобальная роль пользователя в системе.

Семантика по умолчанию (может уточняться бизнес-логикой):
- "superadmin" : полный доступ ко всем тенантам и всем проектам,
                 игнорирует проектные роли (projectRole).
- "admin"      : админ внутри своего тенанта, может создавать проекты,
                 управлять ими и участниками (с учётом projectRole).
- "reviewer"   : может просматривать результаты проверок, отчёты,
                 аудит (read-only, но шире, чем viewer).
- "editor"     : может вносить изменения в рамках разрешённых проектов
                 (загрузка документов, запуск анализов и т.п.).
- "viewer"     : только просмотр в рамках разрешённых проектов.
- "user"       : базовая роль, обычно минимальные права.
- "system"     : техническая роль для системных задач/заглушек dev-режима.

ВНИМАНИЕ:
- GlobalRole НЕ используется напрямую в таблице deal_members.
- Для проверки прав на конкретный проект используется комбинация:
  global_role (GlobalRole) + project_role (ProjectRole).
"""


__all__ = [
    "ProjectRole",
    "GlobalRole",
]
