# src/classifiers/language_detector.py

"""
Определение языка текста по доле кириллических символов.

Назначение:
- Дать очень быстрый и предсказуемый признак языка для каскада классификации.
- Используется там, где достаточно грубого деления «русский / не русский».

Алгоритм:
- Считаем количество символов в диапазоне Юникода для кириллицы.
- Вычисляем отношение: (кол-во кириллических символов) / (длина текста).
- Если доля кириллицы >= 20% → считаем, что текст на русском (код 'ru').
- Иначе возвращаем 'en' как «по умолчанию не‑русский» текст.

Ограничения:
- Этот детектор не различает другие языки (de, fr, es и т.п.).
- Для более точного мног язычного детекта можно позже заменить реализацию
  на библиотеку наподобие langdetect или pycld3, но это будет дороже по ресурсам.
"""

from __future__ import annotations


class LanguageDetector:
    """
    Простой детектор языка на основе доли кириллицы.

    Порог:
    - Если в тексте хотя бы 20% символов — кириллические,
      считаем язык 'ru', иначе — 'en'.
    """

    def detect(self, text: str) -> str:
        """
        Определить язык текста.

        Параметры:
        - text: исходный текст документа в любом регистре.

        Возвращает:
        - 'ru' — если текст преимущественно кириллический.
        - 'en' — во всех остальных случаях (английский или любой иной «не‑ru»).

        Особые случаи:
        - Пустая строка → возвращаем 'ru' как дефолт (система ориентирована на RU).
        """
        if not text:
            return "ru"

        total = len(text)
        cyrillic = sum(1 for ch in text if "\u0400" <= ch <= "\u04ff")
        ratio = cyrillic / max(total, 1)

        return "ru" if ratio >= 0.20 else "en"
