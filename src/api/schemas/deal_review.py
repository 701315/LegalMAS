# src/api/schemas/deal_review.py

"""
DTO schemas for the deal review UI API.

These models describe the "ready-made" JSON for the frontend:
- Document list with risk statuses;
- Detailed document card with checks;
- DD request list;
- Conditional checks list;
- Extracted values list (structured values).

They are independent of internal ORM models and AggregatedResults —
a mapping layer exists between them in deal_review_service.
"""

from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, Field, StrictBool, field_validator


class DocumentSummaryDTO(BaseModel):
    """
    Brief document status for the deal document list.

    Shows:
    - Document name and type;
    - Status (pending / classified / quarantine, etc.);
    - Risk counts by severity level;
    - Whether there are structural issues (degraded);
    - Classification level and confidence.
    """

    document_id: str
    name: str
    doc_type: str
    status: str

    critical_count: int
    high_count: int
    medium_count: int
    pass_count: int
    unclear_count: int

    has_degraded_structure: bool
    in_quarantine: bool

    classification_level: str
    classification_confidence: float


class CheckItemDTO(BaseModel):
    """
    A single check result for a document in the detailed card view.

    Includes:
    - Check identifier and name;
    - Result and severity;
    - Short evidence snippet;
    - Confidence and detector used;
    - Quality flags;
    - Conditional check metadata;
    - structured_data with extracted fields;
    - (optional) segment metadata for multi-document files.

    Canonical display semantics (NEW):
        display_text        — primary human-readable factual result text.
                              Generated by result_semantics.py in result_saver.
                              Frontend renders it as primary cell text.
        review_status       — canonical workflow status:
                              "needs_review" | "ok" | "not_applicable" | "unclear"
        review_message      — advisory explanation for the lawyer (system recommendation).
        needs_manual_review — explicit workflow flag: True → requires manual review.
        ui_mode             — semantic check type: "clause_presence" | "extraction" |
                              "risk_flag" | "comparison" | "summary" | None.
    """

    check_id: str
    check_name: str
    result: str
    severity: str
    evidence_snippet: str | None
    page: int | None
    clause_uid: str
    confidence: float | None
    detector_used: str | None
    quality_flags: dict | None
    conditional_check_triggered: bool
    trigger_name: str | None
    structured_data: dict[str, Any]
    origin: str | None = None

    # Segment metadata (optional, for multi-document physical files)
    segment_id: str | None = None
    segment_type: str | None = None
    segment_title: str | None = None
    segment_order: int | None = None
    is_primary_segment: bool | None = None

    # Canonical display semantics — source of truth for primary cell text.
    # None means result_semantics did not produce text (legacy run or n/a).
    # Frontend falls back to review_status label in this case.
    display_text: str | None = None
    review_status: str | None = None
    review_message: str | None = None
    needs_manual_review: bool = False
    ui_mode: str | None = None

    # Locale-specific presentation metadata.
    # Existing fields above remain the effective fields to render.
    output_locale: str | None = None
    presentation_locale: str | None = None  # Deprecated: use output_locale
    presentation_content_version: str | None = None
    presentation_source_locale: str | None = None
    presentation_status: str | None = None
    presentation_is_fallback: bool = True

    # Present only when a ready/reviewed/approved presentation safely replaced
    # canonical content. They support a future "show original" UI action.
    canonical_check_name: str | None = None
    canonical_display_text: str | None = None
    canonical_review_message: str | None = None


