class DDGridV1ResponseDTO(BaseModel):
    """
    Full hierarchical DD Grid V1 structure for a single run.

    Endpoint: GET /deals/{deal_id}/runs/{run_id}/dd-grid-v1

    Structure:
    - global_groups: hierarchy of global checks
      (group → checks → columns). Sort: display_order → label.
    - doc_type_classes: hierarchy by document types
      (registry group → type → checks). Empty branches are hidden.
    - column_registry: all runtime columns (column_id → spec).
      column_id format: '{check_id}__{field_key}'.
    - cell_values: {doc_id: {segment_id: {column_id: CellValueDTO}}}.
      Cell = intersection of (document, segment, runtime column).
      segment_id = "_default" for single-segment documents.
    - drawer_contents: {doc_id: {segment_id: {check_id: DrawerDTO}}}.
      Drawer = detail panel shown on cell click.
      segment_id = "_default" for single-segment documents.
    - documents_meta: document metadata, sorted by filename.

    Cell states:
      defined      — value found, display_value formatted.
      not_defined  — check executed, value not found.
      not_executed — check was not executed (plan exists, no result).
      error        — technical execution error.

    Check applicability is guaranteed by the planner:
    a cell is created only if the check was scheduled (plan_item exists).
    not_applicable is not used as a state.

    Location contract:
      location_source: 'per_field' → exact pinpoint.
      location_source: 'canonical_check' | 'display_text' → approximate.
      location_source: 'none' → no location available.
      clause_ref/page may be null when no pinpoint is available.

    See docs/dd_grid_v1_contract.md for the full API contract.
    """

    deal_id: str
    run_id: str

    # Effective locale resolved for this response.
    output_locale: str | None = None
    presentation_locale: str | None = None  # Deprecated: use output_locale

    global_groups: list[DDGridGlobalGroupDTO]
    doc_type_classes: list[DDGridDocTypeClassDTO]
    column_registry: dict[str, DDGridColumnDTO]
    cell_values: dict[str, dict[str, dict[str, DDGridCellValueDTO]]]
    drawer_contents: dict[str, dict[str, dict[str, DDGridDrawerDTO]]]
    documents_meta: list[DDGridDocumentMetaDTO]


