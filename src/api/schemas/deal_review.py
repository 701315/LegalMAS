class DDGridCellValueDTO(BaseModel):
    """
    Value of a single DD Grid V1 cell.

    Cell = intersection of (document_id, segment_id, column_id).
    column_id format: '{check_id}__{field_key}'.

    cell_state:
      defined      — value found, display_value formatted per column.format.
      not_defined  — check executed, value not found.
      not_executed — check was not executed for this document/segment.
      error        — technical execution error.

    Check applicability is guaranteed by the planner:
    a cell is created only if the check was scheduled (plan_item exists).
    not_applicable is not used as a state.

    Location contract:
      location_source: 'per_field' | 'canonical_check' | 'display_text' | 'none'.
      - per_field       — LLM returned explicit structured_data[field].location → exact.
      - canonical_check — top-level CheckResult.page + clause_uid → approximate.
      - display_text    — heuristic extracted from display_text → approximate.
      - none            — no location (or suppressed for negative findings).
      location_confidence: 'high' (exact) or 'low'/'medium' (approximate).
      clause_ref and page may be null when no pinpoint is available.
    """

    cell_state: str
    """defined | not_defined | not_executed | error"""

    display_value: str
    """Ready-to-display text for the cell. Formatted per column.format."""

    raw_value: Any = None
    """Raw value from structured_data (for tooltip / drill-down)."""

    location_source: Literal[
        "per_field",
        "canonical_check",
        "display_text",
        "none",
    ] = "none"
    """Which pipeline stage produced the anchor:
    - per_field       — LLM returned explicit structured_data[field].location
    - canonical_check — top-level CheckResult.page + clause_uid (post-B0.2)
    - display_text    — heuristic extracted from display_text
    - none            — no location available (incl. all non-defined cells)
    """

    location_clause_ref: str | None = None
    """Clause reference (e.g., 'cl. 22'). None when fallback without pinpoint."""

    location_clause_uid: str | None = None
    """Effective clause UID (e.g., 'main_contract:7.2'). Used by viewer
    to match activeChunk in sizedChunks[].clauseUids. None when unavailable."""

    location_page: int | None = None
    """Page number in the document. None when fallback without pinpoint."""

    location_confidence: str | None = None
    """'high' — exact; 'low'/'medium' — approximate. None if location is absent."""


