class DDGridDrawerDTO(BaseModel):
    """
    Drawer content for a single (document_id, check_id).

    Displayed when clicking on a DD Grid cell / row.

    reason: result explanation. Precedence:
      1. metadata field 'reason'
      2. metadata field 'explanation'
      3. metadata field 'notes'
      4. review_message (from CheckResult)
      5. display_text (from CheckResult)
      Reason-like fields are not duplicated in evidence_items.

    fields: detail for each runtime column of the check.
      cell_state, display_value, raw_value, location (exact or fallback).

    evidence_items: list of evidence references from EVIDENCE_LIST fields.
      reason/explanation/notes are not included here.

    cell_state: aggregate cell_state across all check columns.
      Priority: error > defined > not_defined > not_executed > not_applicable.

    Additionally:
    - detection_level / confidence / quality_flags provide result transparency;
    - qc_* fields contain the QC audit trail without a separate round-trip;
    - execution_status is returned in the API contract:
      SUCCESS | PARTIAL | FAILED | TIMEOUT | SKIPPED | IN_PROGRESS.
      IN_PROGRESS means the check is still running (Run not yet completed).
    """

    check_id: str
    check_name: str
    document_id: str
    cell_state: str
    reason: str | None = None
    review_status: str | None = None
    review_message: str | None = None
    display_text: str | None = None

    # Locale-specific presentation metadata for the check-level drawer text.
    output_locale: str | None = None
    presentation_locale: str | None = None  # Deprecated: use output_locale
    presentation_content_version: str | None = None
    presentation_source_locale: str | None = None
    presentation_status: str | None = None
    presentation_is_fallback: bool = True

    # Original canonical drawer content when a safe localized presentation
    # has been selected.
    canonical_check_name: str | None = None
    canonical_display_text: str | None = None
    canonical_review_message: str | None = None

    execution_status: str | None = None
    """
    Check execution status:
      SUCCESS     — completed successfully, all fields found.
      PARTIAL     — completed, some fields not found.
      FAILED      — technical error (COMPUTE_FAILED / PERSIST_FAILED / FAILED).
      TIMEOUT     — timeout exceeded.
      SKIPPED     — not applicable to doc_type or not yet started (PENDING).
      IN_PROGRESS — actively running (RUNNING); possible when viewing
                    Grid before Run completion.
    """

    detection_level: DDGridDetectionLevel | None = None
    """L1 | L2 | L3 | L4"""

    confidence: float | None = Field(default=None, ge=0.0, le=1.0)
    """Confidence score 0.0-1.0. None when not applicable or unavailable."""

    quality_flags: dict[str, StrictBool] | None = None
    """
    Open dict of technical quality flags.
    Only true values are allowed.
    None = no technical caveats.
    """

    qc_status: DDGridQCStatus | None = None
    qc_by: str | None = None
    qc_at: str | None = None
    qc_comment: str | None = None

    # Observability (B3 P1)
    agent_name: str | None = None
    """
    Agent/detector name. Derived from detector_used.
    Examples: 'RulesDetector', 'LLMDetector', 'HybridDetector', 'ExtractionExecutor'.
    None for legacy runs or if detector_used is unknown.
    """

    model_version: str | None = None
    """
    LLM model version. E.g.: 'qwen-2.5-7b', 'gpt-4-turbo-2024-04-09'.
    None for L1/L4 without LLM or if data is unavailable.
    """

    execution_time_ms: int | None = Field(default=None, ge=0, le=600000)
    """
    Check execution time in milliseconds.
    Derived from started_at / finished_at.
    None if data is unavailable or delta <= 0.
    """

    retry_attempts: int | None = Field(default=None, ge=1)
    """
    Number of LLM retry attempts. 1 = succeeded on first try.
    None for L1 without LLM or if data is unavailable.
    """

    input_tokens: int | None = Field(default=None, ge=0)
    """
    Number of input tokens (context + prompt overhead).
    None if LLM was not invoked or data is unavailable.
    """

    output_tokens: int | None = Field(default=None, ge=0)
    """
    Number of output tokens.
    None if LLM was not invoked or data is unavailable.
    """

    fields: list[DDGridDrawerFieldDTO] = Field(default_factory=list)
    evidence_items: list[str] = Field(default_factory=list)

    @field_validator("quality_flags")
    @classmethod
    def validate_quality_flags(
        cls,
        value: dict[str, StrictBool] | None,
    ) -> dict[str, StrictBool] | None:
        """
        quality_flags:
        - None if no flags;
        - non-empty dict;
        - only non-empty keys;
        - only true boolean values.
        """
        if value is None:
            return None

        normalized: dict[str, StrictBool] = {}
        for key, flag in value.items():
            normalized_key = str(key).strip()
            if not normalized_key:
                raise ValueError("quality_flags keys must be non-empty strings")
            if flag is not True:
                raise ValueError("quality_flags must contain only true boolean values")
            normalized[normalized_key] = True

        if not normalized:
            raise ValueError("quality_flags must be None or contain at least one true flag")

        return normalized

    @field_validator("qc_at")
    @classmethod
    def validate_qc_at(cls, value: str | None) -> str | None:
        """
        qc_at must be an ISO 8601 string or None.
        Empty string is normalized to None.
        """
        if value is None:
            return None

        normalized = value.strip()
        if not normalized:
            return None

        try:
            datetime.fromisoformat(normalized.replace("Z", "+00:00"))
        except ValueError as exc:
            raise ValueError("qc_at must be a valid ISO 8601 datetime string") from exc

        return normalized


