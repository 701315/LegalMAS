# Регулярные выражения для TOC
# ============================================================================

DOT_LEADER_RE = re.compile(
    r"""
    (?:
        [\.\·•_]{3,}
        |
        (?:\.\s*){3,}
    )
    """,
    re.VERBOSE,
)

