# src/services/structure/_segmenter/config.py

"""
Числовые пороги и лимиты сегментации.

Все настраиваемые константы вынесены сюда, чтобы:
- не дублировать magic numbers по модулям;
- упростить тюнинг порогов;
- облегчить тестирование граничных условий.
"""

from __future__ import annotations

# ── Минимальные расстояния и окна ─────────────────────────────────────────────

MIN_ELEMENTS_BETWEEN_BOUNDARIES: int = 3
"""Минимальное количество элементов между двумя соседними границами."""

MAX_REASONABLE_SEGMENTS: int = 15
"""Максимально допустимое количество сегментов; при превышении — fallback."""

NEW_PAGE_HEADING_WINDOW: int = 3
"""Количество элементов от начала страницы, в пределах которых heading
считается «верхушкой страницы»."""

# ── Артефакты повторяющихся заголовков ────────────────────────────────────────

MIN_PAGES_FOR_ARTIFACT: int = 3
"""Минимальное количество страниц с одинаковым текстом, чтобы считать его
running header / page artifact."""

MAX_HEADER_LINES_TO_CHECK: int = 5
"""Сколько первых элементов каждой страницы проверять на running header."""

# ── Пороги уверенности ────────────────────────────────────────────────────────

DEFAULT_SEGMENT_CONFIDENCE_THRESHOLD: float = 0.70
"""Порог уверенности, выше которого boundary candidate принимается."""

WEAK_BOUNDARY_THRESHOLD: float = 0.45
"""Порог, ниже которого boundary candidate отбрасывается полностью."""

# ── Purity recovery ──────────────────────────────────────────────────────────

PURITY_RESCAN_MAX_PASSES: int = 3
"""Максимальное количество итераций post-segmentation purity recovery."""


